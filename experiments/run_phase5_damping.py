"""Phase 5: PRE-REGISTERED test of confidence damping.

REGISTERED BEFORE ANY PHASE 5 RUN. The commit that introduces this file
contains the registration and no results; the run follows in a later commit,
and the history timestamps the order.

WHY THIS PHASE EXISTS, AND WHY IT IS NOT A RE-TEST
  Phase 4 pre-registered NA(fp_filter) and found it adoptable but not
  demonstrably effective. In the exploratory part of that analysis, NA(damp) --
  the arm the Phase 4 registration demoted -- outperformed the registered
  primary on six of eight conditions and reached raw significance on five of
  six SZZ sources against zero for the filter.

  That observation is EXPLORATORY. It was generated by the Phase 4 data, so
  testing it on the Phase 4 data would confirm a hypothesis on the sample that
  produced it, which is the practice pre-registration exists to prevent. It is
  recorded here as motivation and is NOT evidence for anything below.

  This phase therefore tests damping on data that DOES NOT YET EXIST. The
  noise-injection grid -- four profiles crossed with six doses -- has never
  been run with the noise-aware models: Phase 3 ran plain ORB across that grid,
  and Phase 4 ran the models on real labels plus a single injected condition at
  one dose. The grid below is new measurement, and the hypotheses are about
  its shape rather than about a mean difference already observed.

REGISTERED HYPOTHESES
  H1  primary     NA(damp) > ORB, averaged across the fp_heavy dose curve.
                  Project-paired, mcc_avg, uniform-latency arm.

  H2  dose trend  NA(damp)'s advantage over ORB INCREASES with fp_heavy dose.
                  Spearman rho(dose, advantage) > 0, one-sided. If damping
                  works by down-weighting suspect positive labels, more such
                  labels should mean more benefit. A flat or negative trend
                  falsifies the stated mechanism even if H1 passes.

  H3  the sharp one, and it is counterintuitive.
                  Chapter 6 measured that at fn_heavy doses >= 0.20 the stream
                  retains essentially NO genuine defect labels while still
                  carrying ~204 positive labels, every one of them false. If
                  damping suppresses the influence of wrong positive labels,
                  its advantage over ORB at fn_heavy dose >= 0.20 should EXCEED
                  its advantage under fp_heavy at matched dose -- because the
                  positive stream there is entirely wrong rather than merely
                  partly wrong.
                  PREDICTION: advantage(fn_heavy, dose>=0.20)
                            > advantage(fp_heavy, dose>=0.20).
                  This is the hypothesis most likely to fail, and it is
                  registered because failing it would show that damping's
                  benefit does not come from the mechanism claimed for it.

  H4  operation   NA(damp) > NA(fp_filter) under fp_heavy.
                  Phase 4's reading was that under label scarcity down-weighting
                  a suspect label beats discarding it. This tests that directly
                  on new data, at the Phase 4 frozen filter configuration.

  ND  gate        At the lowest dose (0.05), NA(damp) does not significantly
                  degrade against ORB. TOST, margin +-0.02 mcc_avg. Failure
                  kills adoptability whatever H1-H4 do.

  All tests: project-paired Wilcoxon on mcc_avg, Hodges-Lehmann with bootstrap
  CI, matched-pairs rank-biserial, Holm within this five-test family. Both
  estimators recorded; mcc_avg primary. Everything else is exploratory and
  labelled so.

SCOPE AND EXCLUSIONS
  Reporting is on the 18 projects that are not in HELD_OUT_PROJECTS. Damping is
  NOT tuned -- it runs at library defaults, so it has no tuning set and nothing
  to leak. NA(fp_filter) carries the Phase 4 frozen configuration unchanged.
  The uniform-latency arm is primary because it isolates noise mechanics from
  arrival scheduling; the no-latency arm is a secondary control.

Outputs (results/phase5/): phase5_results.csv, phase5_tests.csv

Usage:
  python -m experiments.run_phase5_damping --fast
  python -m experiments.run_phase5_damping
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import numpy as np
import pandas as pd
from scipy.stats import spearmanr, wilcoxon

BASE_DIR = Path(__file__).resolve().parent.parent
sys.path.append(str(BASE_DIR))

from codebase.config import ORB_CONFIG, RANDOM_SEEDS, FP_FILTER_CONFIG
from codebase.data.loader import (load_or_build_dataset, get_all_projects,
                                  get_project_dataset)
from codebase.evaluation.metrics import paired_effect
from codebase.evaluation.regimes import prequential_latency
from codebase.noise.injection import (load_bias_profiles, symmetric_noise,
                                      asymmetric_noise)
from codebase.online.orb import OOB, ORB
from codebase.online.noise_aware_orb import NoiseAwareORB, FPFilterORB
from experiments.run_phase2_impact import _holm
from experiments.run_phase4_na_orb import HELD_OUT_PROJECTS

OUT = BASE_DIR / "results" / "phase5"
OUT.mkdir(parents=True, exist_ok=True)

DOSES = [0.05, 0.10, 0.15, 0.20, 0.25, 0.30]
PROFILES = ["symmetric", "fp_heavy", "mid", "fn_heavy"]
PROFILE_SOURCES = {"fp_heavy": "BSZZ", "mid": "RASZZ", "fn_heavy": "LSZZ"}
ARMS = ["uniform", "none"]
TOST_MARGIN = 0.02
HIGH_DOSE = 0.20        # the fn_heavy annihilation regime, fixed in advance


def models(seed: int) -> dict:
    base = dict(ORB_CONFIG)
    return {
        "OOB": OOB(n_estimators=base.get("n_estimators", 20), seed=seed),
        "ORB": ORB(seed=seed, **base),
        "NA(damp)": NoiseAwareORB(seed=seed, use_damp=True, use_rescue=False, **base),
        "NA(fp_filter)": FPFilterORB(seed=seed, **FP_FILTER_CONFIG, **base),
    }


def make_noisy(y, profile, dose, seed, profiles):
    if profile == "symmetric":
        return symmetric_noise(y, dose, seed)
    rho0, rho1 = profiles[PROFILE_SOURCES[profile]]
    return asymmetric_noise(y, dose, rho0, rho1, seed)


def run_project(df, project, seeds, profiles) -> list:
    y = df["label_oracle"].to_numpy(dtype=int)
    rows = []
    for seed in seeds:
        for profile in PROFILES:
            for dose in DOSES:
                noisy = make_noisy(y, profile, dose, seed, profiles)
                d = df.copy(); d["label_noisy"] = noisy
                for arm in ARMS:
                    for name, m in models(seed).items():
                        r = prequential_latency(m, d, "label_noisy",
                                                eval_label_col="label_oracle",
                                                latency_mode=arm)
                        rows.append(dict(
                            project=project, seed=seed, profile=profile,
                            dose=dose, latency=arm, model=name,
                            n_pos_noisy=int((noisy == 1).sum()),
                            n_pos_retained=int(((y == 1) & (noisy == 1)).sum()),
                            mcc_avg=r["mcc_avg"], gmean_avg=r["gmean_avg"],
                            mcc=r["mcc"], gmean=r["gmean"]))
    return rows


def _adv(res, profile, model_a, model_b, arm="uniform", doses=None):
    """Project-level advantage of model_a over model_b, averaged over doses."""
    sub = res[(res.profile == profile) & (res.latency == arm)]
    if doses is not None:
        sub = sub[sub.dose.isin(doses)]
    pm = sub.groupby(["project", "model"])["mcc_avg"].mean().unstack()
    if model_a not in pm or model_b not in pm:
        return None
    return pm[[model_a, model_b]].dropna()


def analyse(res: pd.DataFrame) -> pd.DataFrame:
    tests = []

    def record(tag, pair, note=""):
        if pair is None or len(pair) < 6:
            return
        a, b = pair.columns
        e = paired_effect(pair[a].to_numpy(), pair[b].to_numpy())
        tests.append(dict(test=tag, A=a, B=b, n=len(pair),
                          mean_A=float(pair[a].mean()), mean_B=float(pair[b].mean()),
                          hodges_lehmann=e["hodges_lehmann"], ci_low=e["ci_low"],
                          ci_high=e["ci_high"], rank_biserial=e["rank_biserial"],
                          n_favouring_A=int((pair[a] > pair[b]).sum()),
                          p=e["p_value"], note=note))

    # H1
    record("H1_damp_vs_orb_fp_heavy", _adv(res, "fp_heavy", "NA(damp)", "ORB"))

    # H4
    record("H4_damp_vs_filter_fp_heavy",
           _adv(res, "fp_heavy", "NA(damp)", "NA(fp_filter)"))

    # ND at the lowest dose
    record("ND_damp_vs_orb_lowest_dose",
           _adv(res, "fp_heavy", "NA(damp)", "ORB", doses=[min(DOSES)]),
           note="non-degradation gate")

    # H3: fn_heavy high-dose advantage vs fp_heavy high-dose advantage
    hi = [d for d in DOSES if d >= HIGH_DOSE]
    fn = _adv(res, "fn_heavy", "NA(damp)", "ORB", doses=hi)
    fp = _adv(res, "fp_heavy", "NA(damp)", "ORB", doses=hi)
    if fn is not None and fp is not None:
        idx = fn.index.intersection(fp.index)
        gap = pd.DataFrame({
            "adv_fn_heavy": fn.loc[idx].iloc[:, 0] - fn.loc[idx].iloc[:, 1],
            "adv_fp_heavy": fp.loc[idx].iloc[:, 0] - fp.loc[idx].iloc[:, 1]})
        record("H3_fn_heavy_adv_exceeds_fp_heavy", gap,
               note=f"doses >= {HIGH_DOSE}")

    out = pd.DataFrame(tests)
    if not out.empty:
        out["p_holm"] = _holm(out["p"].to_numpy())

    # H2: does the advantage grow with dose?
    sub = res[(res.profile == "fp_heavy") & (res.latency == "uniform")]
    pm = sub.groupby(["dose", "project", "model"])["mcc_avg"].mean().unstack()
    if {"NA(damp)", "ORB"} <= set(pm.columns):
        per_dose = (pm["NA(damp)"] - pm["ORB"]).groupby(level="dose").mean()
        rho, pv = spearmanr(per_dose.index.values, per_dose.values)
        one_sided = pv / 2 if rho > 0 else 1 - pv / 2
        h2 = pd.DataFrame([dict(test="H2_advantage_grows_with_dose",
                                A="NA(damp)", B="ORB", n=len(per_dose),
                                spearman_rho=round(float(rho), 4),
                                p=round(float(one_sided), 4),
                                note="; ".join(f"{d:.2f}:{v:+.4f}"
                                               for d, v in per_dose.items()))])
        out = pd.concat([out, h2], ignore_index=True)

    # TOST on the ND gate
    nd = _adv(res, "fp_heavy", "NA(damp)", "ORB", doses=[min(DOSES)])
    if nd is not None and len(nd) >= 6:
        d = (nd.iloc[:, 0] - nd.iloc[:, 1]).to_numpy()
        pl = wilcoxon(d + TOST_MARGIN, alternative="greater").pvalue
        pu = wilcoxon(d - TOST_MARGIN, alternative="less").pvalue
        out = pd.concat([out, pd.DataFrame([dict(
            test="ND_TOST_equivalence", A="NA(damp)", B="ORB", n=len(d),
            p=float(max(pl, pu)),
            note=f"margin +-{TOST_MARGIN}; equivalent="
                 f"{bool(max(pl, pu) < 0.05)}")])], ignore_index=True)
    return out


def main(fast: bool):
    df_all = load_or_build_dataset()
    profiles = load_bias_profiles()
    projects = [p for p in get_all_projects(df_all) if p not in HELD_OUT_PROJECTS]
    seeds = RANDOM_SEEDS[:3] if fast else RANDOM_SEEDS
    if fast:
        projects = projects[:5]

    rows = []
    for p in projects:
        print(f">>> {p}", flush=True)
        rows += run_project(get_project_dataset(p, df_all), p, seeds, profiles)
        pd.DataFrame(rows).to_csv(OUT / "phase5_results.csv", index=False)

    res = pd.DataFrame(rows)
    res.to_csv(OUT / "phase5_results.csv", index=False)
    tests = analyse(res)
    tests.to_csv(OUT / "phase5_tests.csv", index=False)

    pd.set_option("display.width", 240)
    print(f"\n=== Phase 5, {res.project.nunique()} reporting projects "
          f"(3 held out), uniform-latency arm primary ===")
    print("\n=== Mean mcc_avg by profile x model (uniform arm) ===")
    print(res[res.latency == "uniform"].groupby(["profile", "model"])["mcc_avg"]
             .mean().unstack().round(4).to_string())
    print("\n=== Registered tests ===")
    if tests.empty:
        print("  (none: need >= 6 paired projects)")
    else:
        cols = [c for c in ["test", "A", "B", "hodges_lehmann", "ci_low", "ci_high",
                            "rank_biserial", "n_favouring_A", "spearman_rho",
                            "p", "p_holm", "note"] if c in tests.columns]
        print(tests[cols].round(4).to_string(index=False))
    print(f"\nSaved to {OUT}/")


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--fast", action="store_true")
    main(ap.parse_args().fast)
